import 'dart:typed_data';

/// A variable length code table, looked up with the next [bits] bits of the
/// stream.
///
/// A code is written as a string of '0' and '1'; a trailing 's' is the sign
/// bit, and a code with it stands for two entries whose second has [a]
/// negated. An entry packs a (signed), b (0..255) and the code length.
class Vlc {
  final int bits;
  final Int32List _table;

  Vlc(this.bits, List<(String, int, int)> codes)
      : _table = Int32List(1 << bits) {
    for (final (code, a, b) in codes) {
      if (code.endsWith('s')) {
        final body = code.substring(0, code.length - 1);
        _add('${body}0', a, b);
        _add('${body}1', -a, b);
      } else {
        _add(code, a, b);
      }
    }
  }

  void _add(String code, int a, int b) {
    final n = code.length;
    final prefix = int.parse(code, radix: 2) << (bits - n);
    final entry = a << 16 | (b & 0xff) << 8 | n;
    for (var i = 0; i < 1 << (bits - n); i++) {
      if (_table[prefix | i] != 0) {
        throw StateError('code $code overlaps another code');
      }
      _table[prefix | i] = entry;
    }
  }

  /// the entry for the next [bits] bits, or 0 when no code matches
  int lookup(int next) => _table[next];

  static int lengthOf(int entry) => entry & 0xff;
  static int aOf(int entry) => entry >> 16;
  static int bOf(int entry) => (entry >> 8) & 0xff;
}

