Vlc _dctTable({required bool first, required bool one}) {
  final codes = <(String, int, int)>[];
  // a is the level, b the run
  void add(List<(String, int, int)> list) {
    for (final (code, run, level) in list) {
      codes.add((code, level, run));
    }
  }

  if (one) {
    codes.add(('0110', 0, dctEnd));
    add(_dct1);
    // table one codes these in its own short codes
    const moved = {(0, 8), (0, 9), (0, 10), (0, 11), (1, 5), (2, 4)};
    add([
      for (final e in _dctCommon)
        if (!moved.contains((e.$2, e.$3))) e
    ]);
  } else {
    if (first) {
      codes.add(('1s', 1, 0));
    } else {
      codes.add(('10', 0, dctEnd));
      codes.add(('11s', 1, 0));
    }
    add(_dct0);
    add(_dctCommon);
  }
  codes.add(('000001', 0, dctEscape));
  return Vlc(17, codes);
}
