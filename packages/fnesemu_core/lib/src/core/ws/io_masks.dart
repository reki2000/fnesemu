// The I/O port masks measured on the hardware by WSHWTest
// (https://github.com/FluBBaOfWard/WSHWTest). The low byte holds the bits
// which can be written and the high byte holds the bits which always read
// as 1. 0xffff marks the ports which are not simple registers.

/// returns the mask of the [port] on the WonderSwan, or on the WonderSwan
/// Color in the mono or [colorMode]
int ioMask(int port, {required bool color, required bool colorMode}) {
  if (port >= _masksMono.length) return 0xffff;
  if (!color) return _masksMono[port];
  return colorMode ? _masksColor[port] : _masksColorInMono[port];
}

