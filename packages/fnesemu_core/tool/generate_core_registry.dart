import 'dart:io';

/// Regenerate composition after adding/removing modules; GUI never changes.
void main() {
  final packageName = RegExp(r'^name:\s*(\S+)', multiLine: true)
      .firstMatch(File('pubspec.yaml').readAsStringSync())!
      .group(1)!;
  final selfPrefix = 'package:$packageName/';
  bool sourcesAvailable(File file, Set<String> visited) {
    if (!file.existsSync()) return false;
    if (!visited.add(file.absolute.path)) return true;
    final directives =
        RegExp(r'^(?:import|export|part)\s+(?!of\b)[^;]*;', multiLine: true);
    final uris = RegExp(r'''['"]([^'"]+)['"]''');
    for (final directive in directives.allMatches(file.readAsStringSync())) {
      for (final match in uris.allMatches(directive.group(0)!)) {
        final uri = match.group(1)!;
        if (uri.startsWith('dart:')) continue;
        final File dependency;
        if (uri.startsWith(selfPrefix)) {
          dependency = File('lib/${uri.substring(selfPrefix.length)}');
        } else if (uri.startsWith('package:')) {
          continue;
        } else {
          dependency = File.fromUri(file.absolute.uri.resolve(uri));
        }
        if (!sourcesAvailable(dependency, visited)) return false;
      }
    }
    return true;
  }

  final modules = Directory('lib/src/core')
      .listSync()
      .whereType<Directory>()
      .where((dir) => File('${dir.path}/module.dart').existsSync())
      .where((dir) =>
          sourcesAvailable(File('${dir.path}/module.dart'), <String>{}))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  final output =
      StringBuffer('// Generated by tool/generate_core_registry.dart.\n');
  for (var i = 0; i < modules.length; i++) {
    final folder = modules[i].path.split('/').last;
    output.writeln("import '../core/$folder/module.dart' as module$i;");
  }
  output.writeln("import '../core_module.dart';");
  output.writeln();
  if (modules.isEmpty) {
    output.writeln('List<CoreModule> createInstalledCoreModules() => [];');
  } else {
    output.writeln('List<CoreModule> createInstalledCoreModules() => [');
    for (var i = 0; i < modules.length; i++) {
      output.writeln('      module$i.createModule(),');
    }
    output.writeln('    ];');
  }
  File('lib/src/internal/core_registry_generated.dart')
      .writeAsStringSync(output.toString());
}
