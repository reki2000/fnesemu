/// A program that fills work RAM, DMAs it to VRAM, sets a CGRAM colour, runs an HDMA channel into the BG1 horizontal scroll, enables VBlank NMI and a vertical timer IRQ, then counts in work RAM; the handler counts in work RAM and cartridge RAM.
Uint8List _rom() {
  final rom = loRom(sramSizeByte: 3);
  // The native-mode NMI and IRQ vectors also point at the handler at $9000.
  rom[0x7fea] = 0x00;
  rom[0x7feb] = 0x90;
  rom[0x7fee] = 0x00;
  rom[0x7fef] = 0x90;
  put(rom, 0x0000, [
    0x18, 0xfb, // CLC; XCE (native mode)
    0xc2, 0x10, // REP #$10 (16-bit X, 8-bit A)
    0xa2, 0xff, 0x01, 0x9a, // LDX #$01ff; TXS
    0xa9, 0x0f, 0x8d, 0x00, 0x21, // INIDISP = $0f
    0xa9, 0x01, 0x8d, 0x05, 0x21, // BGMODE = 1
    0xa9, 0x00, 0x8d, 0x07, 0x21, // BG1SC = 0
    0xa9, 0x01, 0x8d, 0x0b, 0x21, // BG12NBA = 1
    0xa9, 0x01, 0x8d, 0x2c, 0x21, // TM = BG1
    0xa9, 0x80, 0x8d, 0x15, 0x21, // VMAIN = $80
    // Sixteen pattern bytes into work RAM $7e0000 through WMDATA.
    0xa9, 0x00, 0x8d, 0x81, 0x21, 0x8d, 0x82, 0x21, 0x8d, 0x83, 0x21,
    0xa9, 0x5a, 0x8d, 0x80, 0x21, 0xa9, 0xa5, 0x8d, 0x80, 0x21,
    0xa9, 0x3c, 0x8d, 0x80, 0x21, 0xa9, 0xc3, 0x8d, 0x80, 0x21,
    0xa9, 0x11, 0x8d, 0x80, 0x21, 0xa9, 0x22, 0x8d, 0x80, 0x21,
    0xa9, 0x33, 0x8d, 0x80, 0x21, 0xa9, 0x44, 0x8d, 0x80, 0x21,
    0xa9, 0x55, 0x8d, 0x80, 0x21, 0xa9, 0x66, 0x8d, 0x80, 0x21,
    0xa9, 0x77, 0x8d, 0x80, 0x21, 0xa9, 0x88, 0x8d, 0x80, 0x21,
    0xa9, 0x99, 0x8d, 0x80, 0x21, 0xa9, 0xaa, 0x8d, 0x80, 0x21,
    // CGRAM colour 1 = $2c7f.
    0xa9, 0x02, 0x8d, 0x21, 0x21, 0xa9, 0x7f, 0x8d, 0x22, 0x21,
    0xa9, 0x2c, 0x8d, 0x22, 0x21,
    // The HDMA table at $7e0100: two two-line entries, then the terminator.
    0xa9, 0x00, 0x8d, 0x81, 0x21, 0xa9, 0x01, 0x8d, 0x82, 0x21,
    0xa9, 0x02, 0x8d, 0x80, 0x21, 0xa9, 0x20, 0x8d, 0x80, 0x21,
    0xa9, 0x00, 0x8d, 0x80, 0x21, 0xa9, 0x02, 0x8d, 0x80, 0x21,
    0xa9, 0x40, 0x8d, 0x80, 0x21, 0xa9, 0x00, 0x8d, 0x80, 0x21,
    0xa9, 0x00, 0x8d, 0x80, 0x21,
    // HDMA channel 7 into BG1HOFS, enabled.
    0xa9, 0x02, 0x8d, 0x70, 0x43, 0xa9, 0x0d, 0x8d, 0x71, 0x43,
    0xa9, 0x00, 0x8d, 0x72, 0x43, 0xa9, 0x01, 0x8d, 0x73, 0x43,
    0xa9, 0x7e, 0x8d, 0x74, 0x43, 0xa9, 0x80, 0x8d, 0x0c, 0x42,
    // DMA channel 0 copies the sixteen work RAM bytes to VRAM at word 0.
    0xa9, 0x01, 0x8d, 0x00, 0x43, 0xa9, 0x18, 0x8d, 0x01, 0x43,
    0xa9, 0x00, 0x8d, 0x02, 0x43, 0x8d, 0x03, 0x43, 0xa9, 0x7e,
    0x8d, 0x04, 0x43, 0xa9, 0x10, 0x8d, 0x05, 0x43, 0xa9, 0x00,
    0x8d, 0x06, 0x43, 0x8d, 0x16, 0x21, 0x8d, 0x17, 0x21,
    0xa9, 0x01, 0x8d, 0x0b, 0x42,
    // Timer IRQ on scanline 100 plus VBlank NMI and auto-joypad.
    0xa9, 0x64, 0x8d, 0x09, 0x42, 0xa9, 0x00, 0x8d, 0x0a, 0x42,
    0xa9, 0xa1, 0x8d, 0x00, 0x42,
    // DBR = $7e, so the loop's absolute accesses hit work RAM.
    0xa9, 0x7e, 0x48, 0xab,
    // loop: INC $0020; BRA loop
    0xee, 0x20, 0x00, 0x80, 0xfb,
  ]);
  put(rom, 0x1000, [
    0xee, 0x30, 0x00, // INC $0030 (in the interrupted program's DBR bank)
    0xaf, 0x00, 0x00, 0x70, // LDA $700000 (cartridge RAM)
    0x18, 0x69, 0x01, // CLC; ADC #$01
    0x8f, 0x00, 0x00, 0x70, // STA $700000
    0xad, 0x10, 0x42, // LDA $4210
    0xad, 0x11, 0x42, // LDA $4211
    0x40, // RTI
  ]);
  return rom;
}

/// The SA-1 program of the chips tests: the main CPU points CRV at $8100 and releases the SA-1, which makes its I-RAM writable and stores $42 at $3000.
Uint8List _sa1Rom() {
  final rom = loRom(romType: 0x34, sramSizeByte: 3);
  put(rom, 0x0000, [
    0xa9, 0x00, 0x8d, 0x03, 0x22, // LDA #$00; STA $2203
    0xa9, 0x81, 0x8d, 0x04, 0x22, // LDA #$81; STA $2204 (CRV = $8100)
    0x9c, 0x00, 0x22, // STZ $2200 (release the SA-1 reset)
    0xef, 0x20, 0x00, 0x7e, // loop: INC $7e0020
    0x80, 0xfb, // BRA loop
  ]);
  put(rom, 0x0100, [
    0xa9, 0xff, 0x8d, 0x2a, 0x22, // LDA #$ff; STA $222a (I-RAM writable)
    0xa9, 0x42, 0x8d, 0x00, 0x30, // LDA #$42; STA $3000
    0x80, 0xfe, // BRA *
  ]);
  return rom;
}

Snes _system(Uint8List rom) => Snes()..setRom(rom);

void _frames(Snes snes, int count) {
  for (var i = 0; i < count; i++) {
    expect(snes.runFrame(snes.scanlinesInFrame).stopped, isFalse);
  }
}

void _roundTrip(Uint8List rom) {
  final original = _system(rom);
  _frames(original, 2);
  final state = original.saveState();

  final restored = _system(rom);
  final wram = restored.bus.wram, vram = restored.ppu.vram;
  restored.loadState(state);
  expect(restored.saveState(), state);
  expect(restored.bus.wram, same(wram));
  expect(restored.ppu.vram, same(vram));

  final pcmA = <double>[], pcmB = <double>[];
  original.onAudio((audio) => pcmA.addAll(audio.buffer));
  restored.onAudio((audio) => pcmB.addAll(audio.buffer));
  for (var i = 0; i < 3; i++) {
    _frames(original, 1);
    _frames(restored, 1);
    expect(restored.saveState(), original.saveState());
    expect(restored.imageBuffer().buffer, original.imageBuffer().buffer);
  }
  expect(pcmA, isNotEmpty);
  expect(pcmB, pcmA);
}

void main() {
  test('SNES restores into a fresh instance and continues identically', () {
    final probe = _system(_rom());
    _frames(probe, 2);
    expect(probe.bus.wram[0x20], isNonZero);
    expect(probe.bus.wram[0x30], isNonZero);
    expect(probe.ppu.vram[0], 0x5a);
    expect(probe.ppu.bgs[0].hofs, isNonZero);
    expect(probe.bus.sramRead(0), isNonZero);
    _roundTrip(_rom());
  });

  test('SNES with an SA-1 restores the second CPU and I-RAM', () {
    final probe = _system(_sa1Rom());
    _frames(probe, 2);
    expect(probe.bus.read(0x003000), 0x42);
    expect(probe.bus.sa1, isNotNull);
    _roundTrip(_sa1Rom());
  });

  test('a state of different media fails before mutation', () {
    final original = _system(_rom());
    _frames(original, 1);
    final state = original.saveState();
    final otherRom = _rom();
    otherRom[0x4000] ^= 0xff;
    final other = _system(otherRom);
    _frames(other, 1);
    final before = other.saveState();
    expect(() => other.loadState(state), throwsA(isA<StateMismatch>()));
    expect(other.saveState(), before);
  });
}
