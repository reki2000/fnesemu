import 'dart:convert';

import 'package:fnesemu/core/snes/component/spc7110.dart';
import 'package:test/test.dart';

// the example of the fullsnes documentation: one string compressed in the
// three modes
const _plain =
    'Test123.ABCDABCDAAAAAAAAaaaabbbbccccdddd7654321076543210.Test123';
const _compressed = {
  0: [
    0x68, 0x91, 0x36, 0x15, 0xf8, 0xbf, 0x42, 0x35, 0x2f, 0x67, 0x3d, 0xb7, //
    0xaa, 0x05, 0xb4, 0xf7, 0x70, 0x7a, 0x26, 0x20, 0xea, 0x58, 0x2c, 0x09,
    0x61, 0x00, 0xc5, 0x00, 0x8c, 0x6f, 0xff, 0xd1, 0x42, 0x9d, 0xee, 0x7f,
    0x72, 0x87, 0xdf, 0xd6, 0x5f, 0x92, 0x65, 0x00, 0x00,
  ],
  1: [
    0x4b, 0xf6, 0x80, 0x1e, 0x3a, 0x4c, 0x42, 0x6c, 0xda, 0x16, 0x0f, 0xc6, //
    0x44, 0xed, 0x64, 0x10, 0x77, 0xaf, 0x50, 0x00, 0x05, 0xc0, 0x01, 0x27,
    0x22, 0xb0, 0x83, 0x51, 0x05, 0x32, 0x4a, 0x1e, 0x74, 0x93, 0x08, 0x76,
    0x07, 0xe5, 0x32, 0x12, 0xb4, 0x99, 0x9e, 0x55, 0xa3, 0xf8, 0x00,
  ],
  2: [
    0x13, 0xb3, 0x27, 0xa6, 0xf4, 0x5c, 0xd8, 0xed, 0x6c, 0x6d, 0xf8, 0x76, //
    0x80, 0xa7, 0x87, 0x20, 0x39, 0x4b, 0x37, 0x1a, 0xcc, 0x3f, 0xe4, 0x3d,
    0xbe, 0x65, 0x2d, 0x89, 0x7e, 0x0b, 0x0a, 0xd3, 0x46, 0xd5, 0x0c, 0x1f,
    0xd3, 0x81, 0xf3, 0xad, 0xdd, 0xe8, 0x5c, 0xc0, 0xbd, 0x62, 0xaa, 0xcb,
    0xf8, 0xb5, 0x38, 0x00,
  ],
};

void main() {
  for (final MapEntry(key: mode, value: data) in _compressed.entries) {
    test('decompresses the documented example in mode $mode', () {
      final decoder =
          Spc7110Decoder((a) => a < data.length ? data[a] : 0)..start(mode, 0);
      final out = [for (var i = 0; i < _plain.length; i++) decoder.next()];
      expect(ascii.decode(out, allowInvalid: true), _plain);
    });
  }
}
